-- SnapClass database schema for Supabase
-- Run this entire file in Supabase SQL Editor before using the app.

create extension if not exists pgcrypto;

create table if not exists public.teachers (
    teacher_id bigint generated by default as identity primary key,
    username text not null unique,
    password text not null,
    name text not null
);

create table if not exists public.students (
    student_id bigint generated by default as identity primary key,
    name text not null,
    face_embedding double precision[],
    voice_embedding double precision[]
);

create table if not exists public.subjects (
    subject_id bigint generated by default as identity primary key,
    subject_code text not null unique,
    name text not null,
    section text,
    teacher_id bigint not null references public.teachers(teacher_id) on delete cascade
);

create table if not exists public.subject_students (
    student_id bigint not null references public.students(student_id) on delete cascade,
    subject_id bigint not null references public.subjects(subject_id) on delete cascade,
    primary key (student_id, subject_id)
);

create table if not exists public.attendance_logs (
    attendance_id bigint generated by default as identity primary key,
    student_id bigint not null references public.students(student_id) on delete cascade,
    subject_id bigint not null references public.subjects(subject_id) on delete cascade,
    timestamp timestamptz not null default timezone('utc', now()),
    is_present boolean not null default false,
    unique (student_id, subject_id, timestamp)
);

create index if not exists subjects_teacher_id_idx on public.subjects(teacher_id);
create index if not exists attendance_subject_id_idx on public.attendance_logs(subject_id);
create index if not exists attendance_student_id_idx on public.attendance_logs(student_id);

-- The original app uses the Supabase anonymous key directly, so allow those
-- public API operations. Replace these permissive policies before production.
alter table public.teachers enable row level security;
alter table public.students enable row level security;
alter table public.subjects enable row level security;
alter table public.subject_students enable row level security;
alter table public.attendance_logs enable row level security;

drop policy if exists "Public access for teachers" on public.teachers;
create policy "Public access for teachers" on public.teachers for all using (true) with check (true);

drop policy if exists "Public access for students" on public.students;
create policy "Public access for students" on public.students for all using (true) with check (true);

drop policy if exists "Public access for subjects" on public.subjects;
create policy "Public access for subjects" on public.subjects for all using (true) with check (true);

drop policy if exists "Public access for subject students" on public.subject_students;
create policy "Public access for subject students" on public.subject_students for all using (true) with check (true);

drop policy if exists "Public access for attendance logs" on public.attendance_logs;
create policy "Public access for attendance logs" on public.attendance_logs for all using (true) with check (true);

grant usage, select on sequence public.teachers_teacher_id_seq to anon, authenticated;
grant usage, select on sequence public.students_student_id_seq to anon, authenticated;
grant usage, select on sequence public.subjects_subject_id_seq to anon, authenticated;
grant usage, select on sequence public.attendance_logs_attendance_id_seq to anon, authenticated;

grant select, insert, update, delete on public.teachers to anon, authenticated;
grant select, insert, update, delete on public.students to anon, authenticated;
grant select, insert, update, delete on public.subjects to anon, authenticated;
grant select, insert, update, delete on public.subject_students to anon, authenticated;
grant select, insert, update, delete on public.attendance_logs to anon, authenticated;
